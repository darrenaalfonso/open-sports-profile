#!/usr/bin/env python3
"""Keep the JSON-LD context block in SPEC.md (section 5) in sync with
context/v0.1/context.jsonld, which is the source of truth.

    python3 scripts/sync-spec.py          rewrite the block in SPEC.md
    python3 scripts/sync-spec.py --check  exit 1 if SPEC.md is out of date
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "SPEC.md"
CONTEXT = ROOT / "context" / "v0.1" / "context.jsonld"
BEGIN = "<!-- BEGIN context.jsonld (generated by scripts/sync-spec.py; edit the file, not this block) -->"
END = "<!-- END context.jsonld -->"


def main():
    text = SPEC.read_text()
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        sys.exit("SPEC.md is missing the BEGIN/END context.jsonld markers")

    block = "```json\n" + CONTEXT.read_text().rstrip("\n") + "\n```"
    new = text[: start + len(BEGIN)] + "\n" + block + "\n" + text[end:]

    if "--check" in sys.argv:
        if new != text:
            sys.exit("SPEC.md section 5 is out of date; run scripts/sync-spec.py")
        print("SPEC.md section 5 is up to date")
        return
    if new != text:
        SPEC.write_text(new)
        print("Updated SPEC.md section 5")
    else:
        print("SPEC.md section 5 already up to date")


main()
